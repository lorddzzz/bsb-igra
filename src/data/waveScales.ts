export const WAVE_SCALES: WaveScale[] = PAIRS.map(([left, right], i) => ({
  id: `w${String(i + 1).padStart(2, '0')}`,
  left,
  right,
}))

export function getWaveScale(id: string | undefined): WaveScale {
  return WAVE_SCALES.find((s) => s.id === id) ?? WAVE_SCALES[0]
}
